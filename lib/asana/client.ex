defmodule Asana.Client do
  @moduledoc """
  Default HTTP client for the Asana API.

  Uses `Req` for HTTP and decodes responses into typed structs using
  the `__fields__/1` metadata generated by `oapi_generator`.

  ## Usage

  All generated operation functions accept a `connection` option:

      connection = Asana.Connection.new("my-token")
      Asana.Tasks.get_task("12345", connection: connection)

  """

  @doc """
  Execute an API operation built by a generated operation module.
  """
  @spec request(map) ::
          {:ok, struct() | map | [struct()]} | :ok | {:error, Asana.Error.response()}
  def request(operation) do
    %{method: method, url: url, opts: opts} = operation

    {connection, _opts} = Keyword.pop!(opts, :connection)
    query = normalize_query(operation[:query])

    req_opts =
      [method: method, url: url]
      |> maybe_put(:params, query)
      |> maybe_put_body(operation)

    case Req.request(connection, req_opts) do
      {:ok, %Req.Response{} = response} ->
        decode_response(response, operation.response)

      {:error, _} = error ->
        error
    end
  end

  defp maybe_put(opts, _key, nil), do: opts
  defp maybe_put(opts, _key, []), do: opts
  defp maybe_put(opts, key, value), do: Keyword.put(opts, key, value)

  defp maybe_put_body(opts, %{body: body}) when not is_nil(body) do
    Keyword.put(opts, :json, body)
  end

  defp maybe_put_body(opts, _operation), do: opts

  defp normalize_query(nil), do: nil
  defp normalize_query([]), do: nil

  defp normalize_query(query) when is_list(query) do
    Enum.map(query, fn
      {key, value} when is_list(value) -> {key, Enum.join(value, ",")}
      pair -> pair
    end)
  end

  # --- Response decoding ---

  defp decode_response(%Req.Response{status: status, body: body}, response_types) do
    case find_response_type(status, response_types) do
      nil ->
        {:error, body}

      :null ->
        :ok

      {module, type} ->
        {:ok, decode(body, {module, type})}

      [type] ->
        {:ok, decode(body, [type])}
    end
  end

  defp find_response_type(status, types) do
    Enum.find_value(types, fn
      {^status, type} -> type
      _ -> nil
    end)
  end

  # --- Typed decoder using __fields__/1 ---

  @doc """
  Decode a value according to a type descriptor from `__fields__/1`.
  """
  def decode(nil, _type), do: nil
  def decode(value, :string), do: value
  def decode(value, :integer), do: value
  def decode(value, :number), do: value
  def decode(value, :boolean), do: value
  def decode(value, :map), do: value

  def decode(value, {:string, :date_time}) when is_binary(value) do
    case DateTime.from_iso8601(value) do
      {:ok, dt, _offset} -> dt
      _ -> value
    end
  end

  def decode(value, {:string, :date}) when is_binary(value) do
    case Date.from_iso8601(value) do
      {:ok, date} -> date
      _ -> value
    end
  end

  def decode(value, {:string, _}), do: value
  def decode(value, {:enum, _values}), do: value

  def decode(value, {:union, types}) when is_list(types) do
    decode(value, choose_union(value, types))
  end

  def decode(value, [type]) when is_list(value) do
    Enum.map(value, &decode(&1, type))
  end

  def decode(%{} = value, {module, type}) when is_atom(module) and is_atom(type) do
    if function_exported?(module, :__fields__, 1) do
      decode_struct(value, module, type)
    else
      value
    end
  end

  def decode(value, _type), do: value

  defp decode_struct(map, module, type) do
    base = struct(module)
    typed_fields = collect_typed_fields(module, type)
    struct_keys = Map.keys(base) -- [:__struct__, :__info__]

    {decoded, extra} =
      Enum.reduce(map, {base, %{}}, fn {key, value}, {acc, extras} ->
        atom_key = safe_to_atom(key)

        if atom_key && atom_key in struct_keys do
          field_type = Map.get(typed_fields, atom_key)
          decoded_value = if field_type, do: decode(value, field_type), else: value
          {Map.put(acc, atom_key, decoded_value), extras}
        else
          {acc, Map.put(extras, key, value)}
        end
      end)

    Map.put(decoded, :__info__, extra)
  end

  defp collect_typed_fields(module, primary_type) do
    primary = safe_fields(module, primary_type)

    all_variants =
      [:t, :compact, :base, :response]
      |> Enum.reject(&(&1 == primary_type))
      |> Enum.flat_map(&safe_fields(module, &1))

    Map.new(all_variants) |> Map.merge(Map.new(primary))
  end

  defp safe_fields(module, type) do
    module.__fields__(type)
  rescue
    FunctionClauseError -> []
  end

  defp safe_to_atom(key) when is_binary(key) do
    String.to_existing_atom(key)
  rescue
    ArgumentError -> nil
  end

  defp safe_to_atom(key) when is_atom(key), do: key

  defp choose_union(nil, types) do
    if :null in types, do: :null, else: hd(types)
  end

  defp choose_union(value, types) do
    non_null = Enum.reject(types, &(&1 == :null))

    cond do
      length(non_null) == 1 ->
        hd(non_null)

      is_map(value) ->
        Enum.find(non_null, hd(non_null), fn
          {_module, _type} -> true
          :map -> true
          _ -> false
        end)

      is_list(value) ->
        Enum.find(non_null, hd(non_null), fn
          [_] -> true
          _ -> false
        end)

      is_binary(value) ->
        Enum.find(non_null, hd(non_null), fn
          {:string, _} -> true
          :string -> true
          _ -> false
        end)

      is_number(value) ->
        Enum.find(non_null, hd(non_null), fn
          :number -> true
          :integer -> true
          _ -> false
        end)

      true ->
        hd(non_null)
    end
  end
end
